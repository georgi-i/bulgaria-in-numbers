#!/usr/bin/env python3
"""Fetch regional (NUTS 3 = oblast) indicators for Bulgaria from the Eurostat API
and write them to data/eurostat.js.

Usage:  python3 scripts/update_eurostat.py
No dependencies beyond the Python standard library.
"""
import json
import urllib.parse
import urllib.request
from datetime import date
from pathlib import Path

API = "https://ec.europa.eu/eurostat/api/dissemination/statistics/1.0/data/"
OUT = Path(__file__).resolve().parent.parent / "data" / "eurostat.js"

# NUTS 3 code -> region key used in data/regions.js
NUTS = {
    "BG311": "ВИДИН", "BG312": "МОНТАНА", "BG313": "ВРАЦА", "BG314": "ПЛЕВЕН",
    "BG315": "ЛОВЕЧ", "BG321": "ВЕЛИКО ТЪРНОВО", "BG322": "ГАБРОВО", "BG323": "РУСЕ",
    "BG324": "РАЗГРАД", "BG325": "СИЛИСТРА", "BG331": "ВАРНА", "BG332": "ДОБРИЧ",
    "BG333": "ШУМЕН", "BG334": "ТЪРГОВИЩЕ", "BG341": "БУРГАС", "BG342": "СЛИВЕН",
    "BG343": "ЯМБОЛ", "BG344": "СТАРА ЗАГОРА", "BG411": "СОФИЯ", "BG412": "СОФИЙСКА",
    "BG413": "БЛАГОЕВГРАД", "BG414": "ПЕРНИК", "BG415": "КЮСТЕНДИЛ", "BG421": "ПЛОВДИВ",
    "BG422": "ХАСКОВО", "BG423": "ПАЗАРДЖИК", "BG424": "СМОЛЯН", "BG425": "КЪРДЖАЛИ",
}
GEOS = list(NUTS) + ["BG"]


def fetch(dataset, **params):
    """Return {(geo, time): value} for a single-series query."""
    q = [("lang", "EN")] + [("geo", g) for g in GEOS]
    for k, v in params.items():
        q.append((k, v))
    url = API + dataset + "?" + urllib.parse.urlencode(q)
    with urllib.request.urlopen(url, timeout=60) as r:
        d = json.load(r)
    ids, size = d["id"], d["size"]
    idx = {k: {v: i for i, v in d["dimension"][k]["category"]["index"].items()} for k in ids}
    for k, s in zip(ids, size):
        if s != 1 and k not in ("geo", "time"):
            raise ValueError(f"{dataset}: dimension {k} not fixed ({s} values)")
    out = {}
    for flat, val in d["value"].items():
        flat = int(flat)
        coords = {}
        for k, s in reversed(list(zip(ids, size))):
            coords[k] = idx[k][flat % s]
            flat //= s
        out[(coords["geo"], coords["time"])] = val
    return out


def latest(series, years_back=None):
    """Latest year for which every NUTS 3 region has a value."""
    years = sorted({t for (_, t) in series}, reverse=True)
    for y in years:
        if all((g, y) in series for g in NUTS):
            return y
    raise ValueError("no complete year")


def main():
    since = str(date.today().year - 12)
    series = {
        "pop": fetch("demo_r_pjanaggr3", sex="T", age="TOTAL", unit="NR", sinceTimePeriod=since),
        "pop_0_14": fetch("demo_r_pjanaggr3", sex="T", age="Y_LT15", unit="NR", sinceTimePeriod=since),
        "pop_65plus": fetch("demo_r_pjanaggr3", sex="T", age="Y_GE65", unit="NR", sinceTimePeriod=since),
        "median_age": fetch("demo_r_pjanind3", indic_de="MEDAGEPOP", unit="YR", sinceTimePeriod=since),
        "birth_rate": fetch("demo_r_gind3", indic_de="GBIRTHRT", sinceTimePeriod=since),
        "death_rate": fetch("demo_r_gind3", indic_de="GDEATHRT", sinceTimePeriod=since),
        "migration_rate": fetch("demo_r_gind3", indic_de="CNMIGRATRT", sinceTimePeriod=since),
        "gdp_per_capita": fetch("nama_10r_3gdp", unit="EUR_HAB", sinceTimePeriod=since),
        "area_km2": fetch("reg_area3", landuse="TOTAL", unit="KM2", sinceTimePeriod=since),
    }
    years = {k: latest(v) for k, v in series.items()}

    regions = {}
    for geo, key in list(NUTS.items()) + [("BG", "_BG")]:
        r = {"nuts": geo}
        for k, s in series.items():
            r[k] = s.get((geo, years[k]))
        r["pop_history"] = {
            t: v for (g, t), v in sorted(series["pop"].items()) if g == geo
        }
        regions[key] = r
    # Eurostat does not publish an area total for BG in reg_area3 consistently
    if regions["_BG"]["area_km2"] is None:
        regions["_BG"]["area_km2"] = sum(regions[k]["area_km2"] for k in NUTS.values())

    payload = {
        "source": "Eurostat",
        "fetched": date.today().isoformat(),
        "years": years,
        "regions": regions,
    }
    OUT.write_text(
        "// Generated by scripts/update_eurostat.py — do not edit by hand.\n"
        "window.EUROSTAT = " + json.dumps(payload, ensure_ascii=False, separators=(",", ":")) + ";\n",
        encoding="utf-8",
    )
    print(f"Wrote {OUT}  years={years}")


if __name__ == "__main__":
    main()
