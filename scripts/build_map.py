#!/usr/bin/env python3
"""Build data/map.js (SVG paths for the 28 oblasts) from geoBoundaries ADM1.

Usage:  python3 scripts/build_map.py [path/to/geoBoundaries-BGR-ADM1_simplified.geojson]
Without an argument the file is downloaded from GitHub.
Boundaries: geoBoundaries (www.geoboundaries.org), CC BY 4.0.
"""
import json
import math
import sys
import urllib.request
from pathlib import Path

URL = ("https://github.com/wmgeolab/geoBoundaries/raw/main/releaseData/gbOpen/"
       "BGR/ADM1/geoBoundaries-BGR-ADM1_simplified.geojson")
OUT = Path(__file__).resolve().parent.parent / "data" / "map.js"

ISO = {
    "BG-01": "БЛАГОЕВГРАД", "BG-02": "БУРГАС", "BG-03": "ВАРНА", "BG-04": "ВЕЛИКО ТЪРНОВО",
    "BG-05": "ВИДИН", "BG-06": "ВРАЦА", "BG-07": "ГАБРОВО", "BG-08": "ДОБРИЧ",
    "BG-09": "КЪРДЖАЛИ", "BG-10": "КЮСТЕНДИЛ", "BG-11": "ЛОВЕЧ", "BG-12": "МОНТАНА",
    "BG-13": "ПАЗАРДЖИК", "BG-14": "ПЕРНИК", "BG-15": "ПЛЕВЕН", "BG-16": "ПЛОВДИВ",
    "BG-17": "РАЗГРАД", "BG-18": "РУСЕ", "BG-19": "СИЛИСТРА", "BG-20": "СЛИВЕН",
    "BG-21": "СМОЛЯН", "BG-22": "СОФИЯ", "BG-23": "СОФИЙСКА", "BG-24": "СТАРА ЗАГОРА",
    "BG-25": "ТЪРГОВИЩЕ", "BG-26": "ХАСКОВО", "BG-27": "ШУМЕН", "BG-28": "ЯМБОЛ",
}
WIDTH = 800
LAT0 = 42.7


def main():
    if len(sys.argv) > 1:
        gj = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))
    else:
        with urllib.request.urlopen(URL, timeout=60) as r:
            gj = json.load(r)

    k = math.cos(math.radians(LAT0))
    feats = []
    for f in gj["features"]:
        g = f["geometry"]
        polys = g["coordinates"] if g["type"] == "MultiPolygon" else [g["coordinates"]]
        feats.append((ISO[f["properties"]["shapeISO"]], polys))

    xs = [lon * k for _, ps in feats for p in ps for ring in p for lon, _ in ring]
    ys = [-lat for _, ps in feats for p in ps for ring in p for _, lat in ring]
    minx, maxx, miny, maxy = min(xs), max(xs), min(ys), max(ys)
    s = WIDTH / (maxx - minx)
    height = round((maxy - miny) * s)

    def pt(lon, lat):
        return ((lon * k - minx) * s, (-lat - miny) * s)

    paths, centers = {}, {}
    for key, polys in feats:
        d, best = [], (0, 0, 0)
        for p in polys:
            for i, ring in enumerate(p):
                pts = [pt(*c) for c in ring]
                d.append("M" + "L".join(f"{x:.1f},{y:.1f}" for x, y in pts) + "Z")
                if i == 0:  # area-weighted centroid of outer ring
                    a = cx = cy = 0.0
                    for (x0, y0), (x1, y1) in zip(pts, pts[1:] + pts[:1]):
                        c = x0 * y1 - x1 * y0
                        a += c; cx += (x0 + x1) * c; cy += (y0 + y1) * c
                    if abs(a) > abs(best[0]):
                        best = (a, cx / (3 * a), cy / (3 * a))
        paths[key] = "".join(d)
        centers[key] = [round(best[1], 1), round(best[2], 1)]

    payload = {"width": WIDTH, "height": height, "paths": paths, "centers": centers}
    OUT.write_text(
        "// Generated by scripts/build_map.py from geoBoundaries (CC BY 4.0).\n"
        "window.BG_MAP = " + json.dumps(payload, ensure_ascii=False, separators=(",", ":")) + ";\n",
        encoding="utf-8",
    )
    print(f"Wrote {OUT} ({WIDTH}x{height})")


if __name__ == "__main__":
    main()
