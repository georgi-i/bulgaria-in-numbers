#!/usr/bin/env python3
"""Build data/population.js from GRAO tables of people registered by permanent / current address.

Usage:
  python3 scripts/update_grao.py <municipalities table> [<settlements table>]

Both arguments may be URLs or local files, e.g.
  https://www.grao.bg/tna/t41ob-15-10-2026_1.txt   (по области и общини, monthly)
  https://www.grao.bg/tna/t41nm-15-09-2026_2.txt   (по населени места, quarterly)
Tables are listed at https://www.grao.bg/tables.html
"""
import json
import re
import subprocess
import sys
import urllib.request
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "data" / "population.js"


def load(src):
    if re.match(r"https?://", src):
        try:
            req = urllib.request.Request(src, headers={"User-Agent": "bulgaria-in-numbers"})
            with urllib.request.urlopen(req, timeout=60) as r:
                raw = r.read()
        except OSError:
            # grao.bg sometimes resets Python's TLS handshake; curl usually works
            raw = subprocess.run(["curl", "-sSfL", src], check=True, capture_output=True).stdout
    else:
        raw = Path(src).read_bytes()
    return raw.decode("cp1251")


def date_of(text):
    d, m, y = re.search(r"дата\s+(\d\d)\.(\d\d)\.(\d{4})", text).groups()
    return f"{y}-{m}-{d}"


def cells(line):
    return [c.strip() for c in line.strip().strip("|").split("|")]


def parse_municipalities(text):
    regions, cur = {}, None
    for line in text.splitlines():
        m = re.match(r"\s+област (.+?)\s*$", line)
        if m:
            cur = regions.setdefault(m.group(1), {"settlements": 0, "permanent": 0, "current": 0, "municipalities": []})
            continue
        if not cur or not line.startswith("|") or "Община" in line:
            continue
        c = cells(line)
        if len(c) != 10 or not c[2].isdigit():
            continue
        if c[0].startswith("Всичко"):
            cur.update(settlements=int(c[1]), permanent=int(c[2]), current=int(c[6]))
        else:
            cur["municipalities"].append({"name": c[0].title(), "settlements": int(c[1]),
                                          "permanent": int(c[2]), "current": int(c[6])})
    return regions


def parse_settlements(text):
    out, region = {}, None
    for line in text.splitlines():
        m = re.match(r"\s+област (.+?) община (.+?)\s*$", line)
        if m:
            region = out.setdefault(m.group(1), [])
            continue
        if region is None or not line.startswith("|"):
            continue
        c = cells(line)
        if len(c) == 4 and c[1].isdigit() and not c[0].startswith("Всичко"):
            region.append((c[0], int(c[1]), int(c[2])))
    return out


def pretty(name):
    kind, _, rest = name.partition(".")
    kind = {"ГР": "гр.", "С": "с.", "МАН": "ман."}.get(kind, kind.lower() + ".")
    return kind + " " + rest.title()


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    ob_text = load(sys.argv[1])
    regions = parse_municipalities(ob_text)
    payload = {"date": date_of(ob_text), "regions": regions}

    if len(sys.argv) > 2:
        nm_text = load(sys.argv[2])
        payload["settlements_date"] = date_of(nm_text)
        for key, rows in parse_settlements(nm_text).items():
            r = regions[key]
            cities = sorted((x for x in rows if x[0].startswith("ГР.") and "," not in x[0]), key=lambda x: -x[2])
            r["towns"] = [{"name": pretty(n), "permanent": p, "current": c} for n, p, c in cities[:5]]
            r["villages_total"] = sum(1 for x in rows if not x[0].startswith("ГР."))
            r["empty"] = sum(1 for x in rows if x[2] == 0)           # nobody at current address
            r["under_50"] = sum(1 for x in rows if 0 < x[2] < 50)   # fewer than 50 residents

    assert len(regions) == 28, f"expected 28 regions, got {len(regions)}"
    OUT.write_text(
        "// Generated by scripts/update_grao.py from GRAO tables — do not edit by hand.\n"
        "window.POPULATION = " + json.dumps(payload, ensure_ascii=False, separators=(",", ":")) + ";\n",
        encoding="utf-8",
    )
    print(f"Wrote {OUT}: {payload['date']}, permanent={sum(r['permanent'] for r in regions.values()):,}")


if __name__ == "__main__":
    main()
