#!/usr/bin/env python3
"""Build data/migration.js from two NSI (НСИ) spreadsheets:

  python3 scripts/update_migration.py "<Вътрешна миграция ... по пол.xlsx>" "<Външна миграция по възраст и гражданство ....xlsx>"

Standard library only (the .xlsx files are read directly as zip + XML).
"""
import json
import re
import sys
import xml.etree.ElementTree as ET
import zipfile
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "data" / "migration.js"
M = "{http://schemas.openxmlformats.org/spreadsheetml/2006/main}"

# NUTS 2 statistical regions, in the column order of the NSI table
REGIONS = [
    ("NW", "Северозападен", "North-West"),
    ("NC", "Северен централен", "North-Central"),
    ("NE", "Североизточен", "North-East"),
    ("SE", "Югоизточен", "South-East"),
    ("SW", "Югозападен", "South-West"),
    ("SC", "Южен централен", "South-Central"),
]
ORIGIN_COLS = [3, 4, 5, 6, 8, 9]  # "Изселени от" columns for the regions above


def first_sheet(path):
    z = zipfile.ZipFile(path)
    strings = []
    if "xl/sharedStrings.xml" in z.namelist():
        for si in ET.fromstring(z.read("xl/sharedStrings.xml")).iter(M + "si"):
            strings.append("".join(t.text or "" for t in si.iter(M + "t")))
    sheet = sorted(n for n in z.namelist() if re.match(r"xl/worksheets/sheet\d+\.xml", n))[0]
    rows = []
    for r in ET.fromstring(z.read(sheet)).iter(M + "row"):
        row = {}
        for c in r.iter(M + "c"):
            v = c.find(M + "v")
            idx = 0
            for ch in re.match(r"[A-Z]+", c.get("r")).group():
                idx = idx * 26 + ord(ch) - 64
            if c.get("t") == "inlineStr":
                val = "".join(t.text or "" for t in c.iter(M + "t"))
            elif v is None:
                continue
            elif c.get("t") in ("s", "str"):
                val = strings[int(v.text)] if c.get("t") == "s" else v.text
            else:
                val = float(v.text)
            row[idx - 1] = int(val) if isinstance(val, float) and val.is_integer() else val
        if row:
            rows.append([row.get(i) for i in range(max(row) + 1)])
    return rows


def year_of(rows):
    return int(re.search(r"(20\d\d)", str(rows[0][0])).group(1))


def norm(s):
    return re.sub(r"\s+", " ", str(s or "")).strip()


def internal(path):
    rows = first_sheet(path)
    block = []
    for r in rows:
        label = norm(r[0])
        if label == "Мъже":
            break
        block.append((label, r))
    by = {label: r for label, r in block}
    total = by["Общо за страната"]
    matrix = []  # matrix[to][from]
    for _, bg, _ in REGIONS:
        r = by[bg]
        matrix.append([r[c] for c in ORIGIN_COLS])
    sex = {norm(r[0]): r[1] for r in rows if norm(r[0]) in ("Мъже", "Жени")}
    return {
        "year": year_of(rows),
        "total": total[1],
        "men": sex.get("Мъже"),
        "women": sex.get("Жени"),
        "regions": [{"id": i, "bg": bg, "en": en} for i, bg, en in REGIONS],
        "matrix": matrix,
    }


def external(path):
    rows = first_sheet(path)
    keys = ["total", "bg", "foreign", "eu", "non_eu"]
    imm, emi, ages = None, None, []
    for r in rows:
        label = norm(r[0])
        if len(r) < 11 or not isinstance(r[1], int):
            continue
        a = dict(zip(keys, r[1:6]))
        b = dict(zip(keys, r[6:11]))
        if label == "Общо":
            imm, emi = a, b
        else:
            ages.append({"age": label, "immigrants": a["total"], "emigrants": b["total"]})
    return {"year": year_of(rows), "immigrants": imm, "emigrants": emi, "ages": ages}


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    payload = {"source": "НСИ", "internal": internal(sys.argv[1]), "external": external(sys.argv[2])}
    OUT.write_text(
        "// Generated by scripts/update_migration.py from NSI tables — do not edit by hand.\n"
        "// internal.matrix[to][from]: people who moved between (or within) NUTS 2 statistical regions.\n"
        "window.MIGRATION = " + json.dumps(payload, ensure_ascii=False, separators=(",", ":")) + ";\n",
        encoding="utf-8",
    )
    i, e = payload["internal"], payload["external"]
    print(f"Wrote {OUT}: internal {i['year']} total={i['total']:,}; external {e['year']} "
          f"immigrants={e['immigrants']['total']:,} emigrants={e['emigrants']['total']:,}")


if __name__ == "__main__":
    main()
